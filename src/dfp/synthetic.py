    seed: int = 42
    history_weeks: int = 156
    history_end_week_start: str = "2026-11-16"   # Monday of last complete history week
    future_weeks: int = 104
    skus_per_category: int = 8
    stores_per_region: int = 4
    batch2_weeks: int = 8                         # weeks delivered in the 2nd batch
    pos_duplicate_rate: float = 0.005
    order_duplicate_rate: float = 0.003
    sales_duplicate_rate: float = 0.003
    missing_store_day_rate: float = 0.002
    late_arrival_rate: float = 0.01               # share of POS rows in the 4 weeks before cutoff
    resent_rate: float = 0.002
    restatement_rate: float = 0.0005
    invalid_rate: float = 0.0005
    data_error_spike_rate: float = 0.0001
    alt_date_format_rate: float = 0.003
    promo_approval_horizon_weeks: int = 52        # future promos beyond this stay 'Draft'

    @classmethod
    def from_scale(cls, scale: str = "small", **overrides) -> "SyntheticConfig":
        return cls(**{**SCALES[scale], **overrides})

    @property
    def history_start(self) -> date:
        end = date.fromisoformat(self.history_end_week_start)
        assert end.weekday() == 0, "history_end_week_start must be a Monday"
        return end - timedelta(weeks=self.history_weeks - 1)


