FORMATS = {"sales": "csv", "pos": "csv", "orders": "json", "products": "csv", "promotions": "json", "pricing": "csv",
           "weather": "json", "inventory": "parquet", "stores": "csv", "regions": "csv", "calendar": "csv", "suppliers": "csv"}
DATE_COL = {"sales": "posting_date", "pos": "transaction_date", "orders": "order_date", "weather": "date",
            "inventory": "snapshot_date"}


def _write(df: pd.DataFrame, path: str, fmt: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if fmt == "csv":
        df.to_csv(path, index=False)
    elif fmt == "json":
        df.to_json(path, orient="records", lines=True, date_format="iso")
    elif fmt == "parquet":
        df.to_parquet(path, index=False)
    else:
        raise ValueError(fmt)


def write_batches(bb: BatchBuilder, staging_root: str) -> pd.DataFrame:
    """Write each batch/source as monthly files (transactional) or one file (master/plans). Returns a file manifest."""
    manifest = []
    for batch, sources in bb.batches.items():
        for src, df in sources.items():
            fmt = FORMATS[src]
            base = os.path.join(staging_root, batch, src)
            if src in DATE_COL:
                # month from the event date; unparseable/alt-format dates fall into an 'unknown' file
                month = pd.to_datetime(df[DATE_COL[src]], format="%Y-%m-%d", errors="coerce").dt.strftime("%Y%m").fillna("misc")
                for m, part in df.groupby(month, sort=True):
                    path = os.path.join(base, f"{src}_{batch}_{m}.{fmt}")
                    _write(part, path, fmt)
                    manifest.append((batch, src, path, len(part)))
            else:
                path = os.path.join(base, f"{src}_{batch}.{fmt}")
                _write(df, path, fmt)
                manifest.append((batch, src, path, len(df)))
    return pd.DataFrame(manifest, columns=["batch_id", "source", "path", "rows"])


def write_ground_truth(gen: SyntheticGenerator, bb: BatchBuilder, root: str, cfg: SyntheticConfig, manifest: pd.DataFrame) -> None:
    os.makedirs(root, exist_ok=True)
    gen.truth["sku_demand_patterns"].to_csv(os.path.join(root, "sku_demand_patterns.csv"), index=False)
    gen.truth["genuine_spikes"].to_csv(os.path.join(root, "genuine_demand_spikes.csv"), index=False)
    wd = gen.truth["weekly_demand_truth"].copy()
    wd["week_start"] = gen.weeks[:gen.H].strftime("%Y-%m-%d").values[wd.pop("_week").values]
    wd.to_csv(os.path.join(root, "weekly_demand_truth.csv"), index=False)
    pd.DataFrame(bb.issues).to_csv(os.path.join(root, "injected_issues.csv"), index=False)
    manifest.to_csv(os.path.join(root, "file_manifest.csv"), index=False)
    with open(os.path.join(root, "generation_manifest.json"), "w") as fh:
        json.dump({"notice": SYNTHETIC_NOTICE, "config": asdict(cfg),
                   "history_start": cfg.history_start.isoformat(), "history_end_week_start": cfg.history_end_week_start,
                   "batch2_first_week": gen.cutoff_date.isoformat(), "n_skus": gen.S,
                   "n_stores": len(gen.tables["stores"]), "rows_by_batch_source": manifest.groupby(["batch_id", "source"])["rows"].sum()
                   .reset_index().to_dict(orient="records")}, fh, indent=2, default=str)
    with open(os.path.join(root, "README_SYNTHETIC.txt"), "w") as fh:
        fh.write(SYNTHETIC_NOTICE + "\nThis folder is the answer key for validation only. Pipelines and models must not read it.\n")


def generate_all(cfg: SyntheticConfig, staging_root: str, ground_truth_root: str):
    gen = SyntheticGenerator(cfg).generate()
    bb = BatchBuilder(gen).build()
    manifest = write_batches(bb, staging_root)
    write_ground_truth(gen, bb, ground_truth_root, cfg, manifest)
    return gen, bb, manifest
