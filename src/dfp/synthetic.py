def easter(year: int) -> date:
    """Anonymous Gregorian algorithm."""
    a, b, c = year % 19, year // 100, year % 100
    d, e = b // 4, b % 4
    f = (b + 8) // 25
    g = (b - f + 1) // 3
    h = (19 * a + b - d - g + 15) % 30
    i, k = c // 4, c % 4
    l = (32 + 2 * e + 2 * i - h - k) % 7
    m = (a + 11 * h + 22 * l) // 451
    month = (h + l - 7 * m + 114) // 31
    day = ((h + l - 7 * m + 114) % 31) + 1
    return date(year, month, day)


def _nth_weekday(year: int, month: int, weekday: int, n: int) -> date:
    d = date(year, month, 1)
    d += timedelta(days=(weekday - d.weekday()) % 7)
    return d + timedelta(weeks=n - 1)


def _last_weekday(year: int, month: int, weekday: int) -> date:
    d = date(year + (month == 12), month % 12 + 1, 1) - timedelta(days=1)
    return d - timedelta(days=(d.weekday() - weekday) % 7)


def country_events(year: int) -> Dict[str, Tuple[Dict[date, str], Dict[date, str]]]:
    """Return {country_code: (holidays, festival_days)} for one year."""
    e = easter(year)
    black_friday = _nth_weekday(year, 11, 3, 4) + timedelta(days=1)  # day after 4th Thursday
    xmas_season = {date(year, 12, d): "Christmas" for d in range(15, 25)}

    hol_in = {date(year, 1, 26): "Republic Day", date(year, 8, 15): "Independence Day",
              date(year, 10, 2): "Gandhi Jayanti"}
    fest_in: Dict[date, str] = {}
    if year in DIWALI:
        dw = date.fromisoformat(DIWALI[year])
        hol_in[dw] = "Diwali"
        fest_in.update({dw - timedelta(days=k): "Diwali" for k in range(0, 10)})
    if year in HOLI:
        hl = date.fromisoformat(HOLI[year])
        hol_in[hl] = "Holi"
        fest_in.update({hl - timedelta(days=k): "Holi" for k in range(0, 3)})

    hol_gb = {date(year, 1, 1): "New Year's Day", e - timedelta(days=2): "Good Friday",
              e + timedelta(days=1): "Easter Monday", _nth_weekday(year, 5, 0, 1): "Early May Bank Holiday",
              _last_weekday(year, 5, 0): "Spring Bank Holiday", _last_weekday(year, 8, 0): "Summer Bank Holiday",
              date(year, 12, 25): "Christmas Day", date(year, 12, 26): "Boxing Day"}
    fest_gb = {**xmas_season, **{e - timedelta(days=k): "Easter" for k in range(0, 4)},
               black_friday: "Black Friday"}

    carnival = e - timedelta(days=47)
    hol_br = {date(year, 1, 1): "Confraternização Universal", carnival - timedelta(days=1): "Carnaval",
              carnival: "Carnaval", e - timedelta(days=2): "Sexta-feira Santa", date(year, 4, 21): "Tiradentes",
              date(year, 5, 1): "Dia do Trabalho", date(year, 9, 7): "Independência",
              date(year, 10, 12): "Nossa Senhora Aparecida", date(year, 11, 2): "Finados",
              date(year, 11, 15): "Proclamação da República", date(year, 12, 25): "Natal"}
    fest_br = {**xmas_season, **{carnival - timedelta(days=k): "Carnival" for k in range(0, 5)},
               black_friday: "Black Friday"}
    return {"IN": (hol_in, fest_in), "GB": (hol_gb, fest_gb), "BR": (hol_br, fest_br)}


def build_calendar(start: date, end: date) -> pd.DataFrame:
    days = pd.date_range(start, end, freq="D")
    rows = []
    events = {y: country_events(y) for y in range(start.year, end.year + 1)}
    for cc in ("IN", "GB", "BR"):
        for ts in days:
            d = ts.date()
            hol, fest = events[d.year][cc]
            iso = d.isocalendar()
            rows.append((d, cc, d - timedelta(days=d.weekday()), iso[0], iso[1], d.month, (d.month - 1) // 3 + 1,
                         d.year, d.isoweekday(), d.isoweekday() >= 6, d in hol, hol.get(d), d in fest, fest.get(d)))
    cal = pd.DataFrame(rows, columns=["date", "country_code", "week_start", "iso_year", "iso_week", "month", "quarter",
                                      "year", "day_of_week", "is_weekend", "holiday_flag", "holiday_name",
                                      "festival_flag", "festival_name"])
    return cal


