PRODUCT_COLS = ["sku_id", "product_id", "product_name", "brand", "category", "subcategory", "pack_size", "uom",
                "launch_date", "discontinue_date", "lifecycle_status", "shelf_life", "supplier_id", "unit_cost_usd",
                "last_modified"]


class BatchBuilder:
    """Turns clean generated tables into two realistic, messy delivery batches."""

    def __init__(self, gen: SyntheticGenerator):
        self.g = gen
        self.cfg = gen.cfg
        self.rng = np.random.default_rng(gen.cfg.seed + 1)
        self.issues: List[dict] = []
        self.batches: Dict[str, Dict[str, pd.DataFrame]] = {"batch_001": {}, "batch_002": {}}

    def _log(self, source, issue, ids, batch, detail=""):
        for i in ids:
            self.issues.append(dict(source=source, batch_id=batch, issue_type=issue, record_key=str(i), detail=detail))

    def _sample(self, df, rate, min_n=1):
        n = max(min_n, int(round(len(df) * rate))) if len(df) else 0
        return df.sample(n=min(n, len(df)), random_state=int(self.rng.integers(1e9))) if n else df.iloc[0:0]

    def _split_by_date(self, df, col, is_date_str=True):
        d = pd.to_datetime(df[col]).dt.date
        b1 = df[d < self.g.cutoff_date]
        b2 = df[d >= self.g.cutoff_date]
        return b1.copy(), b2.copy()

    # ---------------------------------------------------------------- POS
    def pos(self):
        cfg, rng = self.cfg, self.rng
        pos = self.g.tables["pos"].drop(columns="_week")
        b1, b2 = self._split_by_date(pos, "transaction_date")
        # missing store-days (records never sent)
        for name, b in (("batch_001", b1), ("batch_002", b2)):
            keys = b[["store_id", "transaction_date"]].drop_duplicates()
            drop = self._sample(keys, cfg.missing_store_day_rate)
            m = b.merge(drop.assign(_d=1), on=["store_id", "transaction_date"], how="left")["_d"].notna().values
            self._log("pos", "missing_store_day", (drop["store_id"] + "|" + drop["transaction_date"]).tolist(), name)
            b.drop(index=b.index[m], inplace=True)
        # late arrivals: rows from the 4 weeks before cutoff delivered in batch 2
        window = pd.to_datetime(b1["transaction_date"]).dt.date >= self.g.cutoff_date - timedelta(days=28)
        late = self._sample(b1[window], cfg.late_arrival_rate)
        b1 = b1.drop(index=late.index)
        self._log("pos", "late_arriving", late["transaction_id"], "batch_002", "event date before cutoff, delivered in batch_002")
        # data-quality defects
        b1, b2 = self._pos_defects(b1, "batch_001"), self._pos_defects(b2, "batch_002")
        # re-sent records (exact copies of batch 1 rows) and restatements (corrected quantity)
        resent = self._sample(b1[b1["transaction_id"].str.startswith("POS-")], cfg.resent_rate)
        self._log("pos", "resent_duplicate_cross_batch", resent["transaction_id"], "batch_002")
        restated = self._sample(b1[(b1["quantity"] > 2) & b1["transaction_id"].str.startswith("POS-")], cfg.restatement_rate).copy()
        restated["quantity"] = restated["quantity"] - 1
        restated["revenue"] = (restated["quantity"] * restated["selling_price"]).round(2)
        self._log("pos", "restatement_latest_wins", restated["transaction_id"], "batch_002", "quantity reduced by 1")
        # schema evolution: batch 2 carries two new columns
        b2 = pd.concat([b2, late, resent, restated], ignore_index=True)
        b2["loyalty_member_flag"] = rng.random(len(b2)) < 0.35
        b2["basket_count"] = np.maximum(1, (b2["quantity"].fillna(1) * rng.uniform(0.6, 0.95, len(b2))).round()).astype(int)
        self.batches["batch_001"]["pos"] = b1
        self.batches["batch_002"]["pos"] = b2.sample(frac=1.0, random_state=7)  # unordered delivery

    def _pos_defects(self, b, batch):
        cfg = self.cfg
        dup = self._sample(b, cfg.pos_duplicate_rate)
        self._log("pos", "exact_duplicate_within_batch", dup["transaction_id"], batch)
        bad = self._sample(b, cfg.invalid_rate * 4)
        parts = np.array_split(bad.index.values, 4)
        b.loc[parts[0], "sku_id"] = "SKU99999"
        self._log("pos", "invalid_sku", b.loc[parts[0], "transaction_id"], batch, "sku not in product master")
        b.loc[parts[1], "store_id"] = None
        self._log("pos", "null_store_id", b.loc[parts[1], "transaction_id"], batch)
        b.loc[parts[2], "quantity"] = -b.loc[parts[2], "quantity"]
        self._log("pos", "negative_quantity", b.loc[parts[2], "transaction_id"], batch)
        b.loc[parts[3], "selling_price"] = None
        self._log("pos", "null_selling_price", b.loc[parts[3], "transaction_id"], batch)
        spike = self._sample(b[b["quantity"] > 0], cfg.data_error_spike_rate)
        b.loc[spike.index, "quantity"] = b.loc[spike.index, "quantity"] * 50
        b.loc[spike.index, "revenue"] = (b.loc[spike.index, "quantity"] * b.loc[spike.index, "selling_price"]).round(2)
        self._log("pos", "data_entry_spike_x50", b.loc[spike.index, "transaction_id"], batch, "keying error, not genuine demand")
        return pd.concat([b, dup], ignore_index=True)

    # ---------------------------------------------------------------- orders & sales
    def orders_sales(self):
        cfg = self.cfg
        orders = self.g.tables["orders"].drop(columns="_week")
        b1, b2 = self._split_by_date(orders, "order_date")
        window = pd.to_datetime(b1["order_date"]).dt.date >= self.g.cutoff_date - timedelta(days=28)
        late = self._sample(b1[window], cfg.late_arrival_rate / 2)
        b1 = b1.drop(index=late.index)
        self._log("orders", "late_arriving", late["order_id"] + "|" + late["order_item"].astype(str), "batch_002")
        out = {}
        for name, b in (("batch_001", b1), ("batch_002", pd.concat([b2, late], ignore_index=True))):
            dup = self._sample(b, cfg.order_duplicate_rate)
            self._log("orders", "exact_duplicate_within_batch", dup["order_id"] + "|" + dup["order_item"].astype(str), name)
            spike = self._sample(b[b["ordered_quantity"] > 5], cfg.data_error_spike_rate * 2)
            b.loc[spike.index, "ordered_quantity"] *= 10
            self._log("orders", "data_entry_spike_x10", spike["order_id"] + "|" + spike["order_item"].astype(str), name,
                      "ordered_quantity keyed x10; confirmed unchanged")
            nulls = self._sample(b, cfg.invalid_rate)
            b.loc[nulls.index, "ordered_quantity"] = None
            self._log("orders", "null_ordered_quantity", nulls["order_id"] + "|" + nulls["order_item"].astype(str), name)
            out[name] = pd.concat([b, dup], ignore_index=True)
        out["batch_002"]["order_source"] = self.rng.choice(["EDI", "Portal", "Sales Rep"], len(out["batch_002"]), p=[0.6, 0.3, 0.1])
        self.batches["batch_001"]["orders"], self.batches["batch_002"]["orders"] = out["batch_001"], out["batch_002"]

        sales = self.g.tables["sales"].drop(columns="_week")
        s1, s2 = self._split_by_date(sales, "posting_date")
        for name, b in (("batch_001", s1), ("batch_002", s2)):
            dup = self._sample(b, cfg.sales_duplicate_rate)
            self._log("sales", "exact_duplicate_within_batch", dup["sales_doc_id"], name)
            alt = self._sample(b, cfg.alt_date_format_rate)
            b.loc[alt.index, "posting_date"] = pd.to_datetime(b.loc[alt.index, "posting_date"]).dt.strftime("%d.%m.%Y")
            self._log("sales", "alt_date_format_dd.MM.yyyy", alt["sales_doc_id"], name)
            self.batches[name]["sales"] = pd.concat([b, dup], ignore_index=True)

    # ---------------------------------------------------------------- other transactional sources
    def others(self):
        g, rng = self.g, self.rng
        # weather: missing days, null humidity, sensor errors
        w = g.tables["weather"]
        w1, w2 = self._split_by_date(w, "date")
        for name, b in (("batch_001", w1), ("batch_002", w2)):
            act = b[b["weather_forecast_type"] == "actual"]
            miss = self._sample(act, 0.005)
            self._log("weather", "missing_day", miss["region_id"] + "|" + miss["date"], name)
            b.drop(index=miss.index, inplace=True)
            nh = self._sample(b, 0.003)
            b.loc[nh.index, "humidity"] = None
            self._log("weather", "null_humidity", nh["region_id"] + "|" + nh["date"], name)
            se = self._sample(b[b["weather_forecast_type"] == "actual"], 0.0005)
            b.loc[se.index, "temperature"] = 99.9
            self._log("weather", "sensor_error_99.9", se["region_id"] + "|" + se["date"], name)
            self.batches[name]["weather"] = b

        inv = g.tables["inventory"].drop(columns="_week")
        i1, i2 = self._split_by_date(inv, "snapshot_date")
        for name, b in (("batch_001", i1), ("batch_002", i2)):
            neg = self._sample(b, 0.001)
            b.loc[neg.index, "on_hand_qty"] = -b.loc[neg.index, "on_hand_qty"].abs() - 1
            self._log("inventory", "negative_on_hand", neg["snapshot_date"] + "|" + neg["sku_id"] + "|" + neg["region_id"], name)
            self.batches[name]["inventory"] = b

        pr = g.tables["pricing"]
        p1, p2 = self._split_by_date(pr, "effective_date")
        typo = self._sample(p1[p1["price_status"] == "Active"], 0.0005, min_n=3)
        p1.loc[typo.index, "current_price"] = p1.loc[typo.index, "current_price"] * 10
        self._log("pricing", "price_keyed_x10", typo["price_record_id"], "batch_001", "unusual price change - data error")
        self.batches["batch_001"]["pricing"], self.batches["batch_002"]["pricing"] = p1, p2

        promo = g.tables["promotions"]
        pm1, pm2 = self._split_by_date(promo, "start_date")
        self.batches["batch_001"]["promotions"], self.batches["batch_002"]["promotions"] = pm1, pm2

    # ---------------------------------------------------------------- masters
    def masters(self):
        g, rng = self.g, self.rng
        prod = g.products
        b1 = prod[prod["lifecycle_status_b1"].notna()].copy()
        b1["lifecycle_status"] = b1["lifecycle_status_b1"]
        b1["last_modified"] = (g.cutoff_date - timedelta(days=1)).isoformat()
        b2 = prod.copy()
        b2["lifecycle_status"] = b2["lifecycle_status_b2"]
        b2["last_modified"] = (g.cutoff_date - timedelta(days=1)).isoformat()
        changed = b2["lifecycle_status_b2"] != b2["lifecycle_status_b1"]
        b2.loc[changed, "last_modified"] = g.hist_end.date().isoformat()
        self._log("products", "scd2_lifecycle_change", b2.loc[changed & prod["lifecycle_status_b1"].notna(), "sku_id"], "batch_002")
        self._log("products", "new_sku_in_batch_002", b2.loc[prod["lifecycle_status_b1"].isna(), "sku_id"], "batch_002")
        # attribute change (SCD2): a brand repositioning renames one product's SKUs
        ren = b2[b2["category"] == "Personal Care"]["product_id"].iloc[0]
        m = b2["product_id"] == ren
        b2.loc[m, "product_name"] = b2.loc[m, "product_name"].str.replace("Dry Spray", "48h Dry Spray")
        b2.loc[m, "last_modified"] = g.hist_end.date().isoformat()
        self._log("products", "scd2_attribute_change_product_name", b2.loc[m, "sku_id"], "batch_002")
        b2["sustainability_tag"] = rng.choice(["Recyclable Pack", "Refill", "Standard", None], len(b2), p=[0.4, 0.15, 0.35, 0.1])
        self.batches["batch_001"]["products"] = b1[PRODUCT_COLS]
        self.batches["batch_002"]["products"] = b2[PRODUCT_COLS + ["sustainability_tag"]]

        st = g.tables["stores"]
        s2 = st.copy()
        i = s2.index[0]
        s2.loc[i, "size_index"] = round(s2.loc[i, "size_index"] * 1.25, 3)
        s2.loc[i, "store_format"] = "Hypermarket"
        s2.loc[i, "last_modified"] = g.hist_end.date().isoformat()
        self._log("stores", "scd1_attribute_change", [s2.loc[i, "store_id"]], "batch_002", "store refit: size_index +25%")
        self.batches["batch_001"]["stores"], self.batches["batch_002"]["stores"] = st, s2
        for t in ("regions", "suppliers", "calendar"):
            self.batches["batch_001"][t] = g.tables[t]

    def build(self) -> "BatchBuilder":
        self.pos()
        self.orders_sales()
        self.others()
        self.masters()
        return self


