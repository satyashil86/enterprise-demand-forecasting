"""Synthetic SAP-style source data generator (Phase 1).

ALL DATA PRODUCED HERE IS SYNTHETIC. Brands, products, stores and customers are invented.

Design
------
1. Master data: regions (3 countries x 2 regions), stores, suppliers, 5-category product
   hierarchy (category > subcategory > brand > product > SKU/pack size).
2. Drivers: daily calendar with country holidays/festivals, daily weather per region,
   change-based price conditions, trade-promotion calendar (history + approved future plans).
3. Demand: a multiplicative weekly demand model per SKU x store with nine demand patterns
   (smooth, seasonal, intermittent, erratic, promotion-driven, price-sensitive,
   weather-sensitive, new product, end-of-life), sampled with negative-binomial noise.
4. Transactions derived from demand: daily POS sell-out -> weekly retailer orders (sell-in,
   the unconstrained demand signal) -> DC inventory simulation -> confirmed orders -> billing.
5. Data-quality issues are injected AFTER generation and logged in a ground-truth file:
   duplicates, missing records, nulls, invalid keys, mixed date formats, data-entry spikes,
   late-arriving records, restated records, schema changes (new columns in batch 2).
6. Output is split into two delivery batches (batch_001 = history up to the cutoff,
   batch_002 = last N weeks + late/restated records + master-data changes).

The ground-truth folder is an answer key for validation only: pipelines and models must never read it.
"""
