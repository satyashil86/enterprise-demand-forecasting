class SyntheticGenerator:
    def __init__(self, cfg: SyntheticConfig):
        self.cfg = cfg
        self.rng = np.random.default_rng(cfg.seed)
        self.H = cfg.history_weeks
        self.F = cfg.future_weeks
        self.weeks = pd.date_range(cfg.history_start, periods=self.H + self.F, freq="W-MON")
        self.hist_end = self.weeks[self.H - 1]                       # last history week start
        self.cutoff_week = self.H - cfg.batch2_weeks                 # first week index of batch 2
        self.cutoff_date = self.weeks[self.cutoff_week].date()
        self.tables: Dict[str, pd.DataFrame] = {}
        self.truth: Dict[str, pd.DataFrame] = {}
        self.issues: List[dict] = []

    # ---------------------------------------------------------------- masters
    def build_masters(self) -> None:
        rng, cfg = self.rng, self.cfg
        reg = pd.DataFrame(REGIONS, columns=["region_id", "region_name", "country", "country_code", "currency",
                                             "hemisphere", "temp_mean", "temp_amp", "temp_peak_doy", "market_factor"])
        self.region_params = reg.set_index("region_id")
        self.tables["regions"] = reg[["region_id", "region_name", "country", "country_code", "currency", "hemisphere"]].copy()

        stores = []
        for r in reg.itertuples():
            for i in range(cfg.stores_per_region):
                ch = STORE_CHANNEL_CYCLE[i % len(STORE_CHANNEL_CYCLE)]
                fmt = STORE_FORMATS[ch]
                fmt = fmt[r.country_code] if isinstance(fmt, dict) else fmt[i % len(fmt)]
                size = rng.uniform(1.0, 2.4) if ch == "E-Commerce" else rng.uniform(0.6, 1.8)
                open_d = cfg.history_start - timedelta(days=int(rng.integers(400, 4000)))
                stores.append((f"ST-{r.region_id}-{i + 1:02d}", f"{r.region_name} {fmt} {i + 1:02d}", r.region_id, ch, fmt,
                               round(size, 3), open_d.isoformat(), "Active", (cfg.history_start - timedelta(days=30)).isoformat()))
        self.tables["stores"] = pd.DataFrame(stores, columns=["store_id", "store_name", "region_id", "channel", "store_format",
                                                              "size_index", "open_date", "status", "last_modified"])

        suppliers = []
        for cat, spec in CATEGORY_SPEC.items():
            for j, ctry in enumerate(["India", "United Kingdom"]):
                lt = int(rng.choice([7, 14, 21, 28]))
                suppliers.append((f"SUP-{spec['code']}-{j + 1:02d}", f"{spec['code']} Manufacturing Plant {j + 1} (synthetic)", ctry, cat,
                                  lt, round(lt * rng.uniform(0.1, 0.3), 1), float(rng.choice([200, 300, 500])),
                                  int(rng.choice([7, 14])), round(rng.uniform(0.85, 0.99), 3)))
        sup = pd.DataFrame(suppliers, columns=["supplier_id", "supplier_name", "country", "category", "lead_time_days",
                                               "lead_time_std_days", "moq", "replenishment_frequency_days", "reliability_score"])
        self.tables["suppliers"] = sup

        prods, sku_idx = [], 0
        n_products = math.ceil(cfg.skus_per_category / 2)
        for cat, spec in CATEGORY_SPEC.items():
            plist = spec["products"]
            for p in range(n_products):
                subcat, pname, brand = plist[p % len(plist)]
                variant = "" if p < len(plist) else f" Variant {p // len(plist) + 1}"
                product_id = f"PRD-{spec['code']}-{p + 1:03d}"
                for k, pack in enumerate(spec["packs"]):
                    j = p * 2 + k
                    if j >= cfg.skus_per_category:
                        break
                    sku_idx += 1
                    pattern = spec["patterns"][j % len(spec["patterns"])]
                    price = spec["base_price"] * rng.uniform(0.8, 1.3) * (1.0 if k == 0 else 2.1)
                    sup_id = f"SUP-{spec['code']}-{(p % 2) + 1:02d}"
                    prods.append(dict(sku_id=f"SKU{sku_idx:05d}", product_id=product_id, product_name=f"{brand} {pname}{variant} {pack}",
                                      brand=brand, category=cat, subcategory=subcat, pack_size=pack,
                                      uom="EA", shelf_life=spec["shelf_life"], supplier_id=sup_id,
                                      unit_cost_usd=round(price * 0.45, 2), _base_price_usd=price, _pattern=pattern,
                                      _pack_factor=1.0 if k == 0 else 0.6))
        prod = pd.DataFrame(prods)
        # lifecycle dates
        H = self.H
        launch_w = np.full(len(prod), -1)
        disc_w = np.full(len(prod), 10_000)
        first_np_done = set()
        for i, r in prod.iterrows():
            if r["_pattern"] == "new_product":
                # Beauty's new product launches 5 weeks before history end -> cold-start test case
                launch_w[i] = H - 5 if r["category"] == "Beauty & Wellbeing" and r["category"] not in first_np_done \
                    else int(rng.integers(55, H - 35))
                first_np_done.add(r["category"])
            if r["_pattern"] == "end_of_life":
                # Home Care EOL is discontinued inside the batch-2 window -> SCD2 status change test
                disc_w[i] = H - 4 if r["category"] == "Home Care" else int(rng.integers(H - 40, H - 14))
        prod["_launch_w"], prod["_disc_w"] = launch_w, disc_w
        hs = cfg.history_start
        prod["launch_date"] = [(hs + timedelta(weeks=int(w))).isoformat() if w >= 0
                               else (hs - timedelta(days=int(rng.integers(300, 3000)))).isoformat() for w in launch_w]
        prod["discontinue_date"] = [(hs + timedelta(weeks=int(w))).isoformat() if w < 10_000 else None for w in disc_w]
        self.products = prod
        self.S = len(prod)

    # ---------------------------------------------------------------- weather
    def build_weather(self) -> None:
        rng = self.rng
        start = self.cfg.history_start
        end = self.hist_end.date() + timedelta(days=6)
        days = pd.date_range(start, end, freq="D")
        doy = days.dayofyear.values
        recs, weekly = [], {}
        for r in self.region_params.itertuples():
            n = len(days)
            seasonal = r.temp_mean + r.temp_amp * np.cos(2 * np.pi * (doy - r.temp_peak_doy) / 365.25)
            ar = np.zeros(n)
            eps = rng.normal(0, 1.6, n)
            for t in range(1, n):
                ar[t] = 0.7 * ar[t - 1] + eps[t]
            temp = seasonal + ar
            extreme = np.zeros(n, dtype=bool)
            # heatwave per year in summer for northern-hemisphere regions, late Jan for Brazil
            for y in sorted(set(days.year)):
                centre = date(y, 7, 15) if r.Index.startswith("UK") else date(y, 5, 10) if r.Index.startswith("IN") else date(y, 1, 25)
                s = centre + timedelta(days=int(rng.integers(-15, 15)))
                idx = np.where((days.date >= s) & (days.date < s + timedelta(days=int(rng.integers(5, 10)))))[0]
                temp[idx] += rng.uniform(5, 8)
                extreme[idx] = True
            month = days.month.values
            if r.Index.startswith("IN"):
                rain_mean = np.where((month >= 6) & (month <= 9), 12.0, 1.0); p_rain = np.where((month >= 6) & (month <= 9), 0.7, 0.1)
            elif r.Index.startswith("UK"):
                rain_mean = np.full(n, 3.5); p_rain = np.full(n, 0.45)
            else:
                rain_mean = np.where((month <= 3) | (month == 12), 8.0, 2.5); p_rain = np.where((month <= 3) | (month == 12), 0.5, 0.25)
            wet = rng.random(n) < p_rain
            rain = np.where(wet, rng.gamma(1.2, rain_mean / 1.2 / np.maximum(p_rain, 0.05) * 0.5, n), 0.0)
            extreme |= rain > 60
            humidity = np.clip(55 + 15 * wet + 0.6 * (rain > 10) * 10 - 0.4 * (temp - r.temp_mean) + rng.normal(0, 6, n), 15, 100)
            df = pd.DataFrame({"region_id": r.Index, "date": days.date, "temperature": temp.round(1), "rainfall": rain.round(1),
                               "humidity": humidity.round(1), "extreme_weather_flag": extreme,
                               "weather_forecast_type": "actual", "forecast_issued_date": None})
            recs.append(df)
            weekly[r.Index] = pd.Series(temp).groupby(np.arange(n) // 7).mean().values  # aligned to Monday starts
            # 14-day short-range forecast issued on the last history day
            fdays = pd.date_range(end + timedelta(days=1), periods=14, freq="D")
            fdoy = fdays.dayofyear.values
            fc_temp = r.temp_mean + r.temp_amp * np.cos(2 * np.pi * (fdoy - r.temp_peak_doy) / 365.25) + \
                ar[-1] * 0.7 ** np.arange(1, 15) + rng.normal(0, 1.0, 14) * np.sqrt(np.arange(1, 15))
            recs.append(pd.DataFrame({"region_id": r.Index, "date": fdays.date, "temperature": fc_temp.round(1),
                                      "rainfall": rng.gamma(1.0, 2.0, 14).round(1), "humidity": rng.uniform(40, 85, 14).round(1),
                                      "extreme_weather_flag": False, "weather_forecast_type": "forecast",
                                      "forecast_issued_date": end.isoformat()}))
        self.tables["weather"] = pd.concat(recs, ignore_index=True)
        self.weekly_temp = np.vstack([weekly[r] for r in self.region_params.index])  # (R, H)

    # ---------------------------------------------------------------- prices
    def build_prices(self) -> None:
        rng, S, T = self.rng, self.S, self.H + self.F
        R = len(self.region_params)
        cc = self.region_params["country_code"].values
        regular = np.zeros((S, R, T))
        competitor = np.zeros((S, R, T))
        planned_change = np.zeros((S, R, T), dtype=bool)
        for s, p in self.products.iterrows():
            for ci, c in enumerate(["IN", "GB", "BR"]):
                ridx = np.where(cc == c)[0]
                base = p["_base_price_usd"] * COUNTRY_FX[c] * COUNTRY_PRICE_LEVEL[c]
                path = np.full(T, base)
                # annual list-price increases (inflation), country-specific magnitude
                infl = {"IN": (0.04, 0.08), "GB": (0.02, 0.06), "BR": (0.04, 0.09)}[c]
                change_w = int(rng.integers(5, 40))
                for w in range(change_w, T, 52):
                    path[w:] *= 1 + rng.uniform(*infl)
                    if w >= self.H:
                        planned_change[s, ridx, w] = True
                if p["_pattern"] == "price_sensitive":
                    w = int(rng.integers(8, 20))
                    while w < self.H:
                        path[w:] *= 1 + rng.choice([-1, 1]) * rng.uniform(0.04, 0.10)
                        w += int(rng.integers(12, 24))
                comp = np.empty(T)
                level = rng.uniform(0.92, 1.08)
                for m in range(0, T, 4):  # monthly competitor observation
                    level = np.clip(level + rng.normal(0, 0.025), 0.85, 1.15)
                    comp[m:m + 4] = level
                for r_i in ridx:
                    regular[s, r_i] = path
                    competitor[s, r_i] = path * comp * rng.uniform(0.98, 1.02)
        # currency rounding
        dec = np.where(np.isin(cc, ["IN"]), 0, 2)
        for r_i in range(R):
            regular[:, r_i] = np.round(regular[:, r_i], dec[r_i])
            competitor[:, r_i] = np.round(competitor[:, r_i], dec[r_i])
        self.regular_price, self.competitor_price, self.planned_price_change = regular, competitor, planned_change

    # ---------------------------------------------------------------- promotions
    def build_promotions(self) -> None:
        rng, S, T, H = self.rng, self.S, self.H + self.F, self.H
        R = len(self.region_params)
        disc = np.zeros((S, R, T))
        display = np.zeros((S, R, T), dtype=bool)
        executed = np.zeros((S, R, T), dtype=bool)
        promo_id_at = np.full((S, R, T), None, dtype=object)
        rows, pid = [], 0
        types = ["TPR", "BOGO", "Display", "Feature", "Bundle"]
        campaigns = ["Summer Saver", "Festive Joy", "Back to School", "Spring Clean", "Healthy Living",
                     "Weekend Deals", "Mega Savings", "New Year Reset"]
        for s, p in self.products.iterrows():
            pp = PATTERN_PARAMS[p["_pattern"]]
            for r_i, region_id in enumerate(self.region_params.index):
                w = int(rng.integers(1, pp["promo_gap"] + 1))
                while w < T:
                    if p["_launch_w"] <= w < p["_disc_w"]:
                        dur = int(rng.choice([1, 2, 2, 3]))
                        ptype = str(rng.choice(types, p=[0.45, 0.15, 0.15, 0.15, 0.10]))
                        d = {"TPR": rng.uniform(10, 30), "BOGO": 50.0, "Display": rng.uniform(0, 8),
                             "Feature": rng.uniform(5, 15), "Bundle": rng.uniform(15, 25)}[ptype]
                        disp = ptype in ("Display", "Feature") or rng.random() < 0.2
                        start = self.weeks[w].date()
                        end = start + timedelta(days=7 * dur - 1)
                        if w < H:
                            status = "Cancelled" if rng.random() < 0.03 else "Executed"
                            approved = start - timedelta(days=int(rng.integers(21, 120)))
                        elif w < H + self.cfg.promo_approval_horizon_weeks:
                            status, approved = "Approved", self.hist_end.date() - timedelta(days=int(rng.integers(1, 90)))
                        else:
                            status, approved = "Draft", None
                        planned = bool(rng.random() < 0.92) if w < H else True
                        pid += 1
                        promo_id = f"PROMO{pid:06d}"
                        rows.append(dict(promotion_id=promo_id, sku_id=p["sku_id"], region_id=region_id, channel="ALL",
                                         start_date=start.isoformat(), end_date=end.isoformat(), promotion_type=ptype,
                                         discount_percentage=round(float(d), 1), display_flag=bool(disp),
                                         marketing_campaign=str(rng.choice(campaigns)), planned_promotion_flag=planned,
                                         promotion_status=status, approved_date=approved.isoformat() if approved else None))
                        if status == "Executed":
                            sl = slice(w, min(w + dur, T))
                            disc[s, r_i, sl] = d
                            display[s, r_i, sl] = disp
                            executed[s, r_i, sl] = True
                            promo_id_at[s, r_i, sl] = promo_id
                        w += dur
                    w += max(2, int(rng.normal(pp["promo_gap"], pp["promo_gap"] * 0.3)))
        self.tables["promotions"] = pd.DataFrame(rows)
        self.promo_disc, self.promo_display, self.promo_active, self.promo_id_at = disc, display, executed, promo_id_at

    # ---------------------------------------------------------------- demand
    def build_demand(self) -> None:
        rng, S, H = self.rng, self.S, self.H
        R = len(self.region_params)
        prod, rp = self.products, self.region_params
        t = np.arange(H)
        woy = np.array([d.isocalendar()[1] for d in self.weeks[:H]])

        # festival weekly flags per country -> names
        cal = self.calendar_df
        fw = cal[(cal["festival_flag"]) & (cal["date"] <= self.hist_end.date() + timedelta(days=6))]
        fest_week = fw.groupby(["country_code", "week_start"])["festival_name"].first()
        week_pos = {d.date(): i for i, d in enumerate(self.weeks[:H])}

        mean = np.zeros((S, R, H))
        genuine_spikes = []
        for s, p in prod.iterrows():
            spec = CATEGORY_SPEC[p["category"]]
            pp = PATTERN_PARAMS[p["_pattern"]]
            base = rng.uniform(*spec["base_units"]) * p["_pack_factor"]
            if p["_pattern"] == "intermittent":
                base *= 0.25
            growth = rng.normal(0.02, 0.04)
            trend = (1 + growth) ** (t / 52.0)
            amp = spec["season_amp"] + pp["season"]
            beta = pp["temp_beta"] if pp["temp_beta"] > 0 else spec["temp_beta"]
            # lifecycle
            life = np.ones(H)
            if p["_launch_w"] >= 0:
                life = 1 / (1 + np.exp(-(t - p["_launch_w"] - 6) / 3.0))
                life[t < p["_launch_w"]] = 0.0
            if p["_disc_w"] < 10_000:
                dw = p["_disc_w"]
                decline = np.clip(1 - 0.85 * (t - (dw - 26)) / 26.0, 0.15, 1.0)
                life = life * np.where(t >= dw - 26, decline, 1.0)
                life[t >= dw] = 0.0
            for r_i, (region_id, r) in enumerate(rp.iterrows()):
                peak = spec["season_peak_week"]
                if spec["climate_season"] and r["hemisphere"] == "S":
                    peak = (peak + 26) % 52
                season = 1 + amp * np.cos(2 * np.pi * (woy - peak) / 52.18)
                weather = np.exp(beta * (self.weekly_temp[r_i, :H] - r["temp_mean"]))
                fest = np.ones(H)
                for (c, ws), name in fest_week.items():
                    if c == r["country_code"] and ws in week_pos:
                        fest[week_pos[ws]] += FESTIVAL_UPLIFT.get(name, {}).get(p["category"], 0.0)
                reg = self.regular_price[s, r_i, :H]
                comp = self.competitor_price[s, r_i, :H]
                el = pp["elasticity"]
                price_mult = (reg / reg[0]) ** el * (reg / comp) ** (0.6 * el)
                d = self.promo_disc[s, r_i, :H]
                promo = 1 + pp["uplift10"] * d / 10.0 + 0.25 * self.promo_display[s, r_i, :H]
                # post-promotion dip (pantry loading) in the week after a promotion ends
                ended = np.r_[False, (d[:-1] > 0) & (d[1:] == 0)]
                promo = promo * np.where(ended, 1 - min(0.35, 0.15 * pp["uplift10"] * 2), 1.0)
                # AR(1) log noise
                e = rng.normal(0, pp["noise"], H)
                ar = np.zeros(H)
                for k in range(1, H):
                    ar[k] = 0.5 * ar[k - 1] + e[k]
                spike = np.ones(H)
                p_spike = 0.03 if p["_pattern"] == "erratic" else 0.003
                hits = np.where(rng.random(H) < p_spike)[0]
                for h in hits:
                    if life[h] > 0:
                        spike[h] = rng.uniform(2, 4) if p["_pattern"] == "erratic" else rng.uniform(1.5, 2.5)
                        genuine_spikes.append((p["sku_id"], region_id, self.weeks[h].date().isoformat(), round(spike[h], 2)))
                mean[s, r_i] = base * r["market_factor"] * trend * season * weather * fest * price_mult * promo * life * spike * np.exp(ar)
        self.region_mean = mean
        self.truth["genuine_spikes"] = pd.DataFrame(genuine_spikes, columns=["sku_id", "region_id", "week_start", "multiplier"])

        # store level
        stores = self.tables["stores"]
        St = len(stores)
        store_region = stores["region_id"].map({r: i for i, r in enumerate(rp.index)}).values
        store_mean = np.zeros((S, St, H))
        listed = np.zeros((S, St), dtype=bool)
        ecom_growth = 1.18 ** (t / 52.0)
        for j, st in stores.iterrows():
            for s, p in prod.iterrows():
                aff = CATEGORY_SPEC[p["category"]]["channel_affinity"][st["channel"]]
                listed[s, j] = rng.random() < (0.9 if aff >= 0.5 else 0.6)
                g = ecom_growth if st["channel"] == "E-Commerce" else 1.0
                store_mean[s, j] = mean[s, store_region[j]] * st["size_index"] * aff * g * listed[s, j] * rng.uniform(0.85, 1.15)
        # sampling
        units = np.zeros((S, St, H), dtype=np.int64)
        for s, p in prod.iterrows():
            pp = PATTERN_PARAMS[p["_pattern"]]
            m = store_mean[s]
            occ = rng.random(m.shape) < pp["p_occ"]
            mm = np.where(occ, m / pp["p_occ"], 0.0)
            k = pp["k"]
            pr = k / (k + np.maximum(mm, 1e-9))
            draw = rng.negative_binomial(k, pr)
            units[s] = np.where(mm > 0, draw, 0)
        self.store_mean, self.store_units, self.listed, self.store_region = store_mean, units, listed, store_region

    # ---------------------------------------------------------------- POS
    def build_pos(self) -> None:
        rng = self.rng
        stores = self.tables["stores"]
        S, St, H = self.store_units.shape
        dow = {"Modern Trade": [0.11, 0.11, 0.12, 0.13, 0.16, 0.21, 0.16],
               "General Trade": [0.14, 0.14, 0.14, 0.14, 0.15, 0.16, 0.13],
               "E-Commerce": [0.15, 0.14, 0.14, 0.14, 0.14, 0.14, 0.15]}
        daily = np.zeros((S, St, H, 7), dtype=np.int64)
        for ch, pv in dow.items():
            js = np.where(stores["channel"].values == ch)[0]
            n = self.store_units[:, js, :]
            daily[:, js] = rng.multinomial(n, pv)
        s_i, j_i, w_i, d_i = np.nonzero(daily)
        qty = daily[s_i, j_i, w_i, d_i]
        r_i = self.store_region[j_i]
        regular = self.regular_price[s_i, r_i, w_i]
        disc = self.promo_disc[s_i, r_i, w_i]
        price = np.round(regular * (1 - disc / 100.0), 2)
        dates = (np.array(self.weeks[:H].values, dtype="datetime64[D]")[w_i] + d_i.astype("timedelta64[D]"))
        date_str = pd.Series(dates).dt.strftime("%Y-%m-%d").values
        sku = self.products["sku_id"].values[s_i]
        sid = stores["store_id"].values[j_i]
        returned = rng.binomial(qty, 0.012)
        pos = pd.DataFrame({
            "transaction_id": pd.Series("POS-" + sid + "-" + sku + "-").str.cat(pd.Series(date_str).str.replace("-", "")),
            "transaction_date": date_str, "sku_id": sku, "store_id": sid,
            "region_id": self.region_params.index.values[r_i], "channel": stores["channel"].values[j_i],
            "quantity": qty.astype(float), "revenue": np.round(qty * price, 2), "selling_price": price,
            "promotion_id": self.promo_id_at[s_i, r_i, w_i], "returned_quantity": returned.astype(float),
        })
        pos["_week"] = w_i
        self.tables["pos"] = pos

    # ---------------------------------------------------------------- orders, inventory, sales
    def build_orders_inventory_sales(self) -> None:
        rng, cfg = self.rng, self.cfg
        stores, prod, rp = self.tables["stores"], self.products, self.region_params
        S, St, H = self.store_units.shape
        R = len(rp)
        net = self.store_units  # retailer sell-out per week
        ch_idx = {c: i for i, c in enumerate(CHANNELS)}
        sell_out = np.zeros((S, R, 3, H))
        for j, st in stores.iterrows():
            sell_out[:, self.store_region[j], ch_idx[st["channel"]]] += net[:, j]
        # retailers order ahead: 70% current week + 30% next week (forward buying), with noise
        nxt = np.concatenate([sell_out[..., 1:], sell_out[..., -1:]], axis=-1)
        ordered = (0.7 * sell_out + 0.3 * nxt) * rng.lognormal(0, 0.08, sell_out.shape)
        # General Trade in India orders fortnightly (lumpy sell-in)
        for r_i, region_id in enumerate(rp.index):
            if region_id.startswith("IN"):
                gt = ordered[:, r_i, ch_idx["General Trade"]]
                both = gt[:, 0:H - 1:2] + gt[:, 1:H:2]
                gt[:, 0:H - 1:2] = both
                gt[:, 1:H:2] = 0
        ordered = np.round(ordered).astype(np.int64)

        # ---- DC inventory simulation per SKU x region (periodic review, order-up-to)
        sup = self.tables["suppliers"].set_index("supplier_id")
        confirmed = np.zeros_like(ordered)
        inv_rows = []
        for s, p in prod.iterrows():
            sp = sup.loc[p["supplier_id"]]
            lt_w = max(1, int(round(sp["lead_time_days"] / 7)))
            rev_w = max(1, int(sp["replenishment_frequency_days"] // 7))
            moq = float(sp["moq"])
            for r_i, region_id in enumerate(rp.index):
                dem = ordered[s, r_i].sum(axis=0).astype(float)                 # (H,)
                avg0 = max(dem[:8].mean(), 1.0)
                on_hand = 3 * avg0
                pipeline: List[Tuple[int, float]] = []                         # (arrival_week, qty)
                unit_cost = p["unit_cost_usd"] * COUNTRY_FX[rp.loc[region_id, "country_code"]]
                for w in range(H):
                    arrived = sum(q for a, q in pipeline if a == w)
                    pipeline = [(a, q) for a, q in pipeline if a > w]
                    on_hand += arrived
                    total = dem[w]
                    ship = min(on_hand, total)
                    fill = ship / total if total > 0 else 1.0
                    on_hand -= ship
                    if total > 0:
                        conf = np.floor(ordered[s, r_i, :, w] * fill).astype(np.int64)
                        confirmed[s, r_i, :, w] = conf
                    hist = dem[max(0, w - 7):w + 1]
                    avg, sd = hist.mean(), hist.std() if len(hist) > 1 else hist.mean() * 0.3
                    safety = 1.65 * sd * math.sqrt(lt_w + rev_w)
                    rop = avg * lt_w + safety
                    if w % rev_w == 0:
                        position = on_hand + sum(q for _, q in pipeline)
                        target = avg * (lt_w + rev_w) + safety
                        need = max(0.0, target - position)
                        if need > 0:
                            qty = math.ceil(need / moq) * moq
                            delay = lt_w + (1 if rng.random() > sp["reliability_score"] else 0)
                            pipeline.append((w + delay, qty))
                    open_po = sum(q for a, q in pipeline if a - w >= lt_w)       # placed, not yet shipped by supplier
                    in_transit = sum(q for a, q in pipeline if a - w < lt_w)
                    inv_rows.append((self.weeks[w].date().isoformat(), p["sku_id"], region_id, f"PL-{region_id}",
                                     round(on_hand, 0), round(in_transit, 0), round(open_po, 0), round(safety, 0),
                                     round(rop, 0), int(sp["lead_time_days"]), moq, int(sp["replenishment_frequency_days"]),
                                     round(unit_cost, 2), rp.loc[region_id, "currency"], w))
        self.tables["inventory"] = pd.DataFrame(inv_rows, columns=[
            "snapshot_date", "sku_id", "region_id", "plant_id", "on_hand_qty", "in_transit_qty", "open_po_qty",
            "safety_stock_qty", "reorder_point_qty", "lead_time_days", "moq", "replenishment_frequency_days",
            "unit_cost", "currency", "_week"])

        # ---- order lines (one order per customer x week, one item per SKU)
        s_i, r_i, c_i, w_i = np.nonzero(ordered)
        oq, cq = ordered[s_i, r_i, c_i, w_i], confirmed[s_i, r_i, c_i, w_i]
        region_ids = rp.index.values[r_i]
        ch_codes = np.array(["MT", "GT", "EC"], dtype=object)[c_i]
        customer = "CUST-" + region_ids + "-" + ch_codes
        week_start = np.array(self.weeks[:H].values, dtype="datetime64[D]")[w_i]
        # one order date per customer-week
        key = pd.Series(customer).str.cat(pd.Series(w_i.astype(str)), sep="|")
        uniq, inv = np.unique(key.values, return_inverse=True)
        offs = rng.integers(0, 5, len(uniq))[inv]
        order_date = week_start + offs.astype("timedelta64[D]")
        req = order_date + rng.integers(3, 8, len(uniq))[inv].astype("timedelta64[D]")
        order_no = pd.Series(inv + 1).map(lambda v: f"SO{4500000000 + v}")
        orders = pd.DataFrame({"order_id": order_no.values, "_sku_order": s_i, "order_date": pd.Series(order_date).dt.strftime("%Y-%m-%d"),
                               "requested_delivery_date": pd.Series(req).dt.strftime("%Y-%m-%d"),
                               "sku_id": prod["sku_id"].values[s_i], "region_id": region_ids,
                               "channel": np.array(CHANNELS)[c_i], "customer_id": customer,
                               "ordered_quantity": oq.astype(float), "confirmed_quantity": cq.astype(float)})
        orders["order_item"] = (orders.groupby("order_id").cumcount() + 1) * 10
        orders["order_status"] = np.where(cq == oq, "Completed", np.where(cq == 0, "Rejected - Stockout", "Partially Confirmed"))
        orders["_week"] = w_i
        orders = orders.drop(columns="_sku_order")
        cols = ["order_id", "order_item", "order_date", "requested_delivery_date", "sku_id", "region_id", "channel",
                "customer_id", "ordered_quantity", "confirmed_quantity", "order_status", "_week"]
        self.tables["orders"] = orders[cols]

        # ---- billing / delivery lines (sell-in shipments)
        sh = orders[orders["confirmed_quantity"] > 0].copy()
        r_map = {r: i for i, r in enumerate(rp.index)}
        s_map = {sku: i for i, sku in enumerate(prod["sku_id"])}
        si = sh["sku_id"].map(s_map).values
        ri = sh["region_id"].map(r_map).values
        list_price = self.regular_price[si, ri, sh["_week"].values]
        trade_disc = np.where(sh["channel"].values == "General Trade", 0.12, np.where(sh["channel"].values == "E-Commerce", 0.10, 0.15))
        posting = pd.to_datetime(sh["requested_delivery_date"]) + pd.to_timedelta(rng.integers(-1, 2, len(sh)), unit="D")
        sales = pd.DataFrame({
            "sales_doc_id": [f"90{70000000 + i}" for i in range(len(sh))], "sales_doc_item": 10, "doc_type": "F2",
            "order_id": sh["order_id"].values, "posting_date": posting.dt.strftime("%Y-%m-%d").values,
            "sku_id": sh["sku_id"].values, "region_id": sh["region_id"].values, "channel": sh["channel"].values,
            "plant_id": "PL-" + sh["region_id"].values, "delivered_quantity": sh["confirmed_quantity"].values,
            "uom": "EA", "net_value": np.round(sh["confirmed_quantity"].values * list_price * (1 - trade_disc), 2),
            "currency": rp.loc[sh["region_id"].values, "currency"].values, "_week": sh["_week"].values})
        self.tables["sales"] = sales
        # ground truth: realised unconstrained demand at modelling grain
        self.truth["weekly_demand_truth"] = orders.groupby(["sku_id", "region_id", "channel", "_week"], as_index=False).agg(
            ordered_quantity=("ordered_quantity", "sum"), confirmed_quantity=("confirmed_quantity", "sum"))

    # ---------------------------------------------------------------- price records
    def build_price_records(self) -> None:
        S, R, T = self.regular_price.shape
        H = self.H
        rp = self.region_params
        rows = []
        for s, sku in enumerate(self.products["sku_id"]):
            for r_i, region_id in enumerate(rp.index):
                reg, comp = self.regular_price[s, r_i], self.competitor_price[s, r_i]
                disc = self.promo_disc[s, r_i]
                cur = np.round(reg * (1 - disc / 100.0), 2)
                prev_cur = None
                for w in range(T):
                    future = w >= H
                    if future and not self.planned_price_change[s, r_i, w]:
                        continue
                    if not future:
                        reasons = []
                        if w == 0:
                            reasons.append("Initial")
                        else:
                            if reg[w] != reg[w - 1]:
                                reasons.append("Regular price change")
                            if disc[w] > 0 and disc[w - 1] == 0:
                                reasons.append("Promotion start")
                            if disc[w] == 0 and disc[w - 1] > 0:
                                reasons.append("Promotion end")
                            if comp[w] != comp[w - 1] and not reasons:
                                reasons.append("Competitor update")
                        if not reasons:
                            continue
                        rows.append((sku, region_id, self.weeks[w].date().isoformat(), reg[w], cur[w] if disc[w] > 0 else None,
                                     prev_cur, cur[w], comp[w], rp.loc[region_id, "currency"], "Active", ";".join(reasons)))
                        prev_cur = cur[w]
                    else:
                        rows.append((sku, region_id, self.weeks[w].date().isoformat(), reg[w], None, reg[w - 1], reg[w], None,
                                     rp.loc[region_id, "currency"], "Planned", "Planned list price increase"))
        df = pd.DataFrame(rows, columns=["sku_id", "region_id", "effective_date", "regular_price", "promotional_price",
                                         "previous_price", "current_price", "competitor_price", "currency",
                                         "price_status", "change_reason"])
        df.insert(0, "price_record_id", [f"PR{i + 1:08d}" for i in range(len(df))])
        self.tables["pricing"] = df

    # ---------------------------------------------------------------- products & calendar tables
    def finalize_masters(self) -> None:
        prod = self.products.copy()
        cutoff_w = self.cutoff_week

        def status(r, as_of_w):
            if r["_launch_w"] > as_of_w:
                return None  # not yet created in master
            if r["_disc_w"] <= as_of_w:
                return "Discontinued"
            if r["_disc_w"] - 26 <= as_of_w:
                return "Phase-Out"
            if r["_launch_w"] >= 0 and as_of_w - r["_launch_w"] < 26:
                return "New"
            return "Active"

        prod["lifecycle_status_b1"] = prod.apply(lambda r: status(r, cutoff_w - 1), axis=1)
        prod["lifecycle_status_b2"] = prod.apply(lambda r: status(r, self.H - 1), axis=1)
        self.products = prod
        self.truth["sku_demand_patterns"] = prod[["sku_id", "category", "brand", "_pattern", "launch_date", "discontinue_date"]] \
            .rename(columns={"_pattern": "synthetic_demand_pattern"})

    # ---------------------------------------------------------------- orchestration
    def generate(self) -> "SyntheticGenerator":
        self.build_masters()
        cal_end = self.weeks[-1].date() + timedelta(days=6)
        self.calendar_df = build_calendar(self.cfg.history_start, cal_end)
        self.build_weather()
        self.build_prices()
        self.build_promotions()
        self.build_demand()
        self.build_pos()
        self.build_orders_inventory_sales()
        self.build_price_records()
        self.finalize_masters()
        cal = self.calendar_df.copy()
        cal["is_future"] = cal["date"] > self.hist_end.date() + timedelta(days=6)
        for c in ("date", "week_start"):
            cal[c] = cal[c].map(lambda d: d.isoformat())
        self.tables["calendar"] = cal
        self.tables["weather"]["date"] = self.tables["weather"]["date"].map(lambda d: d.isoformat())
        return self


